export const MATERIAL_PRIORITY_REASONS: Record<string, string> = new Proxy(REASON_LABELS, {
  get(target, key: string) {
    return target[key] ?? (typeof key === 'string'
      ? key.replaceAll('_', ' ').replace(/^./, first => first.toUpperCase())
      : undefined)
  },
})

export function MaterialHardPriorityPanel({value}:{value:MaterialHardState}) {
  return <div data-testid="material-priority-state" className="mt-3 space-y-3 rounded-lg border border-border bg-bg-primary p-3 text-[11px] leading-relaxed">
    <div className="font-semibold text-text-primary">{value.mode === 'tape' ? 'Piece supply and holding' : 'Independent operations and shared resources'}</div>
    <div className="space-y-1 rounded border border-border bg-bg-secondary px-2 py-2">
      {Object.entries(value.shared).map(([label, state]) => <div key={label} className="flex justify-between gap-2"><span className="text-text-muted">{label}</span><span className="text-right font-medium">{state}</span></div>)}
    </div>
    {value.requests.map(request => <div key={request.id} className="rounded border border-border px-2 py-2">
      <div className="font-semibold">{request.id} · {value.mode === 'web' && request.id === 'SUPPLY' ? 'Upstream feed' : value.mode === 'web' && request.id === 'RECEIVE' ? 'Downstream piece receipt' : request.label}</div>
      <div>{request.progress}</div><div className="text-text-muted">{request.detail}</div>
      {Object.values(value.parts).some(part => part.side === request.id.toLowerCase() && part.status === 'dropped') && <div className="font-medium text-red-700">Vacuum hold lost</div>}
    </div>)}
    {value.violations.map(reason => <div key={reason} className="rounded bg-red-50 px-2 py-2 text-red-700">{MATERIAL_PRIORITY_REASONS[reason]}</div>)}
  </div>
}
